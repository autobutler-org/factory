package main

import (
	"context"
	"flag"
	"fmt"
	"slices"
	"strings"
)

func completionCommand() command {
	return command{
		name:    "completion",
		args:    "<bash|zsh|fish>",
		summary: "Print a shell completion script.",
		about: `Print a completion script for bash, zsh or fish, generated from the command
table, so it completes every command and its flags. Load it with:

  bash:  source <(factory completion bash)
  zsh:   source <(factory completion zsh)
  fish:  factory completion fish | source`,
		setup: func(*flag.FlagSet) runner {
			return func(_ context.Context, args []string, s streams) int {
				switch args[0] {
				case "bash":
					fmt.Fprint(s.out, bashCompletion())
				case "zsh":
					fmt.Fprint(s.out, "autoload -U +X bashcompinit && bashcompinit\n"+bashCompletion())
				case "fish":
					fmt.Fprint(s.out, fishCompletion())
				default:
					return usageError(s, "completion", fmt.Sprintf("no completion for %q; use bash, zsh or fish", args[0]))
				}
				return 0
			}
		},
	}
}

// completions maps what has been typed after factory, as command words, to
// the words that may come next: "" to the top-level words, a group to its
// commands, a command to its flags.
func completions() (prefixes []string, next map[string][]string) {
	next = map[string][]string{}
	add := func(prefix, word string) {
		if !slices.Contains(next[prefix], word) {
			if _, seen := next[prefix]; !seen {
				prefixes = append(prefixes, prefix)
			}
			next[prefix] = append(next[prefix], word)
		}
	}
	for _, c := range commands() {
		words := strings.Fields(c.name)
		for i, w := range words {
			add(strings.Join(words[:i], " "), w)
		}
		fs, _ := c.flags()
		fs.VisitAll(func(f *flag.Flag) { add(c.name, "--"+f.Name) })
		if c.name == "completion" {
			for _, sh := range []string{"bash", "zsh", "fish"} {
				add(c.name, sh)
			}
		}
	}
	// A command's flags are matched as a prefix, so the longest prefix must
	// be tried first.
	slices.SortStableFunc(prefixes, func(a, b string) int { return len(b) - len(a) })
	return prefixes, next
}

// bashCompletion completes the command words typed so far, flags left out,
// against the longest prefix that names a group or a command.
func bashCompletion() string {
	prefixes, next := completions()
	var b strings.Builder
	b.WriteString(`# factory completion for bash; generated by 'factory completion bash'.
_factory() {
  local cur="${COMP_WORDS[COMP_CWORD]}" words=() w
  for w in "${COMP_WORDS[@]:1:COMP_CWORD-1}"; do
    [[ $w == -* ]] || words+=("$w")
  done
  local typed="${words[*]}"
  case "$typed" in
`)
	for _, p := range prefixes {
		pattern := `""`
		if p != "" {
			pattern = fmt.Sprintf(`"%s" | "%s "*`, p, p)
		}
		fmt.Fprintf(&b, "    %s) COMPREPLY=($(compgen -W \"%s\" -- \"$cur\")) ;;\n", pattern, strings.Join(next[p], " "))
	}
	b.WriteString(`  esac
}
complete -F _factory factory
`)
	return b.String()
}

// fishCompletion offers the same words as bashCompletion, under the longest
// typed prefix that names a group or a command.
func fishCompletion() string {
	prefixes, next := completions()
	var b strings.Builder
	quoted := make([]string, len(prefixes))
	for i, p := range prefixes {
		quoted[i] = "'" + p + "'"
	}
	fmt.Fprintf(&b, `# factory completion for fish; generated by 'factory completion fish'.
function __factory_at
    set -l t (commandline -opc)
    set -e t[1]
    set -l typed (string join ' ' (string match -v -- '-*' $t) | string collect)
    for p in %s
        if test "$typed" = "$p"; or string match -q -- "$p *" "$typed"
            test "$p" = "$argv[1]"
            return
        end # if
    end
    return 1
end
complete -c factory -f
`, strings.Join(quoted, " "))
	for _, p := range prefixes {
		for _, w := range next[p] {
			cond := fmt.Sprintf("__factory_at '%s'", p)
			if flagName, isFlag := strings.CutPrefix(w, "--"); isFlag {
				fmt.Fprintf(&b, "complete -c factory -n \"%s\" -l %s\n", cond, flagName)
			} else {
				fmt.Fprintf(&b, "complete -c factory -n \"%s\" -a %s\n", cond, w)
			}
		}
	}
	return b.String()
}
